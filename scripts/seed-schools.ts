import { readFileSync, writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')

interface School {
  name: string
  city: string
  state_province: string
  country: string
}

// ── CSV helpers ──

function parseCSVRow(line: string): string[] {
  const fields: string[] = []
  let current = ''
  let inQuotes = false
  for (let i = 0; i < line.length; i++) {
    const ch = line[i]
    if (inQuotes) {
      if (ch === '"') {
        if (i + 1 < line.length && line[i + 1] === '"') {
          current += '"'
          i++
        } else {
          inQuotes = false
        }
      } else {
        current += ch
      }
    } else if (ch === '"') {
      inQuotes = true
    } else if (ch === ',') {
      fields.push(current)
      current = ''
    } else {
      current += ch
    }
  }
  fields.push(current)
  return fields
}

function escapeSQL(s: string): string {
  return s.replace(/'/g, "''")
}

// ── Parse IPEDS (US institutions) ──

function parseIPEDS(): School[] {
  const raw = readFileSync(resolve(ROOT, 'data/ipeds/HD2023.csv'), 'utf-8')
  const lines = raw.split(/\r?\n/).filter(Boolean)
  const header = parseCSVRow(lines[0])

  const idx = {
    name: header.findIndex((h) => h.replace(/^\uFEFF/, '') === 'INSTNM'),
    city: header.findIndex((h) => h === 'CITY'),
    state: header.findIndex((h) => h === 'STABBR'),
    active: header.findIndex((h) => h === 'CYACTIVE'),
  }

  const schools: School[] = []
  for (let i = 1; i < lines.length; i++) {
    const row = parseCSVRow(lines[i])
    if (row[idx.active]?.trim() !== '1') continue
    const name = row[idx.name]?.trim()
    const city = row[idx.city]?.trim()
    const state = row[idx.state]?.trim()
    if (!name) continue
    schools.push({ name, city, state_province: state, country: 'US' })
  }

  console.log(`  IPEDS: ${schools.length} active US institutions`)
  return schools
}

// ── Parse Hipo JSON (Canadian institutions) ──

interface HipoEntry {
  name: string
  'state-province': string | null
  alpha_two_code: string
  country: string
}

function parseHipoCanada(): School[] {
  const raw = readFileSync(resolve(ROOT, 'data/hipo_universities.json'), 'utf-8')
  const all: HipoEntry[] = JSON.parse(raw)
  const ca = all.filter((u) => u.alpha_two_code === 'CA')
  const schools: School[] = ca.map((u) => ({
    name: u.name.trim(),
    city: '',
    state_province: u['state-province']?.trim() ?? '',
    country: 'CA',
  }))
  console.log(`  Hipo: ${schools.length} Canadian institutions`)
  return schools
}

// ── Parse world-universities CSV (additional Canadian institutions) ──

function parseWorldUniversitiesCanada(): School[] {
  const raw = readFileSync(resolve(ROOT, 'data/world_universities.csv'), 'utf-8')
  const lines = raw.split(/\r?\n/).filter(Boolean)
  const schools: School[] = []
  for (const line of lines) {
    const parts = line.split(',')
    if (parts[0] !== 'CA') continue
    let name = parts[1]?.trim()
    if (!name) continue
    name = name.replace(/^"|"$/g, '')
    if (!name) continue
    schools.push({ name, city: '', state_province: '', country: 'CA' })
  }
  console.log(`  world-universities CSV: ${schools.length} Canadian institutions`)
  return schools
}

// ── Deduplicate ──

function dedup(schools: School[]): School[] {
  const seen = new Map<string, School>()
  for (const s of schools) {
    s.name = s.name.replace(/^"|"$/g, '').trim()
    if (!s.name) continue
    const key = s.name.toLowerCase()
    const existing = seen.get(key)
    if (!existing) {
      seen.set(key, s)
    } else {
      if (!existing.city && s.city) existing.city = s.city
      if (!existing.state_province && s.state_province)
        existing.state_province = s.state_province
    }
  }
  return Array.from(seen.values())
}

// ── Generate SQL ──

function generateSQL(schools: School[]): string {
  const sorted = [...schools].sort((a, b) => {
    if (a.country !== b.country) return a.country === 'US' ? -1 : 1
    return a.name.localeCompare(b.name)
  })

  const lines: string[] = [
    '-- Auto-generated by scripts/seed-schools.ts',
    `-- ${sorted.length} institutions (US + Canada)`,
    `-- Generated: ${new Date().toISOString().slice(0, 10)}`,
    '',
    'INSERT INTO public.schools (name, location, country, state_province, city)',
    'VALUES',
  ]

  const values = sorted.map((s) => {
    const locationParts = [s.city, s.state_province, s.country].filter(Boolean)
    const location = locationParts.join(', ')
    return `  ('${escapeSQL(s.name)}', '${escapeSQL(location)}', '${escapeSQL(s.country)}', '${escapeSQL(s.state_province)}', '${escapeSQL(s.city)}')`
  })

  lines.push(values.join(',\n'))
  lines.push('ON CONFLICT DO NOTHING;')
  lines.push('')

  return lines.join('\n')
}

// ── Main ──

console.log('Parsing data sources...')
const usSchools = parseIPEDS()
const hipoCanada = parseHipoCanada()
const worldCanada = parseWorldUniversitiesCanada()

const allCanada = dedup([...hipoCanada, ...worldCanada])
console.log(`  Merged Canadian (deduplicated): ${allCanada.length}`)

const allSchools = dedup([...usSchools, ...allCanada])
console.log(`\nTotal unique schools: ${allSchools.length}`)

const sql = generateSQL(allSchools)
const outPath = resolve(
  ROOT,
  'packages/supabase/supabase/migrations/20260410100001_seed_schools.sql'
)
writeFileSync(outPath, sql, 'utf-8')
console.log(`\nWrote migration: ${outPath}`)
console.log(`SQL size: ${(sql.length / 1024).toFixed(1)} KB`)
